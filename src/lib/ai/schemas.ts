export function contextValues(patch: z.infer<typeof contextPatchSchema>) {
  const { ticketCents, ...rest } = patch;
  return {
    ...rest,
    ...(ticketCents !== undefined
      ? { ticketCents: ticketCents === null ? null : BigInt(ticketCents) }
      : {}),
  };
}
