const text = z.string().min(1).max(8000);
export const batchItemSchema = z.object({
  ideia: text,
  formato: z.string().max(1000),
  referencia: z.string().max(2000),
  instrucoes_gravacao: z.string().max(2000),
  instrucoes_edicao: z.string().max(2000),
  g1: text,
  g2: text,
  g3: text,
  g4: text,
  corpo: text,
  narrativa: text,
  awareness_entry: awareness,
  awareness_exit: awareness,
  skeleton,
  hipotese: text,
  bloco_testado: block,
  prova_usada: text,
  duracao_estimada: z.number().int().min(5).max(300),
});
export const batchSchema = z.object({
  items: z.array(batchItemSchema).min(1).max(12),
});
// The transcript is stored from the transcription itself, never regenerated by the model.
export const analysisSchema = z.object({
  segments: z
    .array(
      z
        .object({
          start: z.number().nonnegative(),
          end: z.number().nonnegative(),
          block,
          summary: text,
          confidence: z.number().min(0).max(1),
        })
        .refine((s) => s.end >= s.start),
    )
    .max(500),
  narrative: text,
  awareness_entry: awareness,
  awareness_exit: awareness,
  skeleton,
  format: text,
  proof_types: z.array(z.string().max(1000)).max(30),
  cta: text,
  visual_notes: z
    .array(z.object({ timestamp: z.number().nonnegative(), description: text }))
    .max(100),
  uncertainties: z.array(z.string().max(2000)).max(30),
});
export const contextPatchSchema = z
  .object({
    produto: z.string().trim().max(4000).optional(),
    publico: z.string().trim().max(4000).optional(),
    transformacao: z.string().trim().max(4000).optional(),
    mecanismo: z.string().trim().max(4000).optional(),
    ticketCents: z
      .string()
      .regex(/^\d{1,15}$/)
      .nullable()
      .optional(),
    tipoFunil: z.string().trim().max(1000).optional(),
    proximoPassoFunil: z.string().trim().max(1000).optional(),
    provasAutorizadas: z.array(z.string().trim().max(4000)).max(30).optional(),
    objecoes: z.array(z.string().trim().max(4000)).max(30).optional(),
    restricoes: z.array(z.string().trim().max(4000)).max(30).optional(),
    estadoCliente: z
      .enum(["A_validado", "B_sinais", "C_zero"])
      .nullable()
      .optional(),
    especialistaHandle: z.string().trim().max(100).optional(),
    produtoNome: z.string().trim().max(300).optional(),
    notas: z.array(z.string().trim().max(4000)).max(50).optional(),
  })
  .strict();
/** Panels the assistant can point to; each one opens over the conversation. */
export const panelIds = [
  "levas",
  "resultados",
  "integracoes",
  "oferta",
  "perfil",
] as const;
export const publicDataSchema = z.object({
  upload: z.object({ creativeKeys: z.array(z.string()) }),
  batch: z.object({ id: z.uuid(), title: z.string() }),
  /** A batch being generated by the worker; the card follows it until it is ready. */
  generation: z.object({ id: z.uuid(), title: z.string() }),
  panel: z.object({ panel: z.enum(panelIds) }),
  /** Names of the offer fields just saved; values stay out of the card. */
  context: z.object({ fields: z.array(z.string()) }),
});
